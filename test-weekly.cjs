const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const {stripTypeScriptTypes}=require('node:module');
const W=require('./weekly-billing.js');
const plan={id:'p',student_id:'s',status:'active',starts_on:'2026-12-21',ends_before:null,acceptance:{signer_name:'Test'}};
const fees=[{plan_id:'p',student_id:'s',charge_date:'2026-12-21',amount:80},{plan_id:'p',student_id:'s',charge_date:'2026-12-28',amount:80}];
W.set([plan],fees);
assert.equal(W.covers({student_id:'s',lesson_date:'2026-12-25'}),true,'School holiday is covered');
assert.equal(W.covers({student_id:'other',lesson_date:'2026-12-25'}),false,'Other student untouched');
assert.equal(W.financialLessons([{student_id:'s',lesson_date:'2026-12-25',status:'completed'}],'s').length,2,'Weekly place replaces lesson fee');
assert.equal(W.financialLessons([],'s').reduce((a,c)=>a+c.rate_charged,0),160,'No calendar event needed');
assert.equal(W.financialLessons([{student_id:'s',lesson_date:'2026-12-25',status:'cancelled'}],'s').reduce((a,c)=>a+c.rate_charged,0),160,'Cancellation does not waive fee');
assert(W.financialLessons([],'s').every(l=>l.status==='scheduled'),'Future charges never become arrears');
const paid=W.ledger([],[{student_id:'s',amount:100}],'s',l=>l.rate_charged);
assert.deepEqual(paid.map(r=>r.paid),[80,20],'Payments cover oldest charges first');
assert.deepEqual(paid.map(r=>r.left),[0,60]);
W.set([plan],[{...fees[0],amount:0,waived:true},fees[1]]);
assert.equal(W.ledger([],[{student_id:'s',amount:80}],'s',l=>l.rate_charged)[1].paid,80,'Waived fee leaves credit for next week');
W.set([{...plan,ends_before:'2026-12-29'}],fees);
assert.equal(W.covers({student_id:'s',lesson_date:'2027-01-03'}),true,'Final weekly fee covers its whole period');
assert.equal(W.covers({student_id:'s',lesson_date:'2027-01-04'}),false,'Coverage stops after final period');
W.set([{...plan,status:'proposed'}],[]);
assert.equal(W.covers({student_id:'s',lesson_date:'2026-12-25'}),false,'Proposal does not alter billing');
W.set([{...plan,status:'ended',acceptance:null}],[]);
assert.equal(W.covers({student_id:'s',lesson_date:'2026-12-25'}),false,'Withdrawn proposal does not alter billing');
const ts=fs.readFileSync(__dirname+'/supabase/functions/student-portal/index.ts','utf8');
const js=stripTypeScriptTypes(ts,{mode:'strip'}).replace(/^import .*$/mg,'');
new vm.Script(js);
const html=fs.readFileSync(__dirname+'/student.html','utf8');
for(const match of html.matchAll(/<script>([\s\S]*?)<\/script>/g)) new vm.Script(match[1]);
const portalContext={window:{},location:{hash:''}};
vm.runInNewContext(fs.readFileSync(__dirname+'/weekly-portal.js','utf8'),portalContext);
const rendered=portalContext.window.renderWeekly({plan:{...plan,status:'proposed',terms_text:'<script>unsafe</script>',lesson_slot:'Wednesday <img>',weekly_fee:80,notice_days:7,terms_version:'test'},acceptance:null,entries:[],payments:[]});
assert(rendered.includes('&lt;script&gt;unsafe&lt;/script&gt;'),'Terms are escaped');
assert(!rendered.includes('<img>'),'Tutor supplied slot is escaped');
assert(rendered.includes('£80 a week') && !rendered.includes('${'),'Price renders as text, never as a raw template');
const renderedAccepted=portalContext.window.renderWeekly({plan:{...plan,status:'active',terms_text:'x',lesson_slot:'Thu',weekly_fee:62.5,notice_days:7,terms_version:'t'},acceptance:{signer_name:'A',accepted_at:new Date().toISOString(),terms_version:'t'},entries:[],payments:[]});
assert(renderedAccepted.includes('£62.50 a week') && !renderedAccepted.includes('${'),'Accepted card shows the chosen price');
console.log('16 weekly billing assertions, portal escaping, parent page syntax and edge TypeScript syntax passed.');
